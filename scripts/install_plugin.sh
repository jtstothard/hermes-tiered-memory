#!/usr/bin/env bash
#
# install_plugin.sh — install the hermes-tiered-memory plugin into a Hermes home.
#
# Usage:
#   scripts/install_plugin.sh <wheel_path> <HERMES_HOME>
#
# What this does:
#   1. pip-installs the wheel into the current Python environment.
#   2. Lays a thin shim into $HERMES_HOME/plugins/tiered-memory/__init__.py.
#   3. Writes plugin.yaml with a description.
#
# Fails closed if HERMES_HOME is unset, the wheel is missing, or pip install fails.
# Idempotent: re-running upgrades cleanly.
#
set -euo pipefail

# Respect PYTHON override so operators can target a specific interpreter
# (e.g. a Hermes runtime venv on PEP 668 systems). Defaults to python3.
PYTHON="${PYTHON:-python3}"

PLUGIN_NAME="tiered-memory"
PLUGIN_DESCRIPTION="Fail-closed composite-provider: hot L1 (Mnemosyne/SQLite) + warm L2 (Hindsight) for Hermes memory"

die() { echo "ERROR: $*" >&2; exit 1; }

# --- argument validation --------------------------------------------------

WHEEL_PATH="${1:-}"
HERMES_HOME="${2:-}"

[ -n "$WHEEL_PATH" ] || die "Usage: $0 <wheel_path> <HERMES_HOME>"
[ -n "$HERMES_HOME" ] || die "HERMES_HOME is required (pass it as the second argument)"

# Resolve to absolute paths
WHEEL_PATH="$(cd "$(dirname "$WHEEL_PATH")" && pwd)/$(basename "$WHEEL_PATH")"
HERMES_HOME="$(cd "$HERMES_HOME" && pwd)"

[ -f "$WHEEL_PATH" ] || die "Wheel not found: $WHEEL_PATH"
[[ "$WHEEL_PATH" == *.whl ]] || die "Not a wheel file: $WHEEL_PATH"
[ -d "$HERMES_HOME" ] || die "HERMES_HOME does not exist: $HERMES_HOME"

# --- 1. pip install the wheel ---------------------------------------------

echo ">> Installing wheel into current Python environment..."
"$PYTHON" -m pip install --upgrade "$WHEEL_PATH" || die "pip install failed"

# Verify the package is importable
"$PYTHON" -c "import hermes_tiered_memory; print('hermes_tiered_memory', hermes_tiered_memory.__version__)" \
    || die "Package import check failed — wheel installed but not importable"

# --- 2. Lay the plugin shim -----------------------------------------------

PLUGIN_DIR="$HERMES_HOME/plugins/$PLUGIN_NAME"
echo ">> Creating plugin shim at $PLUGIN_DIR ..."
mkdir -p "$PLUGIN_DIR"

cat > "$PLUGIN_DIR/__init__.py" << 'SHIM'
"""Hermes user-installed shim for the hermes-tiered-memory plugin.

This file is generated by scripts/install_plugin.sh.  It re-exports the
real entrypoints from the pip-installed ``hermes_tiered_memory`` package
so the Hermes memory-provider loader can discover and import them.

The loader's discovery heuristic requires one of the literal strings
``register_memory_provider`` or ``MemoryProvider`` to appear in this
file's first 8192 chars.  Both are present below.
"""

from hermes_tiered_memory import register, register_memory_provider, CompositeProvider

__all__ = ["register", "register_memory_provider", "CompositeProvider"]
SHIM

# --- 3. Write plugin.yaml -------------------------------------------------

echo ">> Writing plugin.yaml ..."
cat > "$PLUGIN_DIR/plugin.yaml" << YAML
name: ${PLUGIN_NAME}
description: "${PLUGIN_DESCRIPTION}"
version: "1.0.2"
YAML

echo ""
echo "Done.  Plugin installed at: $PLUGIN_DIR"
echo "Next: set 'memory.provider: ${PLUGIN_NAME}' in your profile config.yaml and restart Hermes."
