#!/usr/bin/env python3
"""Run the fixed prototype harness and emit content-bound evidence.

This is deliberately not release evidence: it records a synthetic/fake boundary.
"""
import hashlib
import json
import os
import pathlib
import platform
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent
REPO_ROOT = ROOT.parent
FIXED_COMMAND = [sys.executable, "-m", "unittest", "discover", "-s", "prototype-acceptance-handoff/tests", "-v"]
DISPLAY_COMMAND = "python3 -m unittest discover -s prototype-acceptance-handoff/tests -v"
# These are the complete executable evidence boundary.  Keep the runner and
# verifier in the same manifest as the harness and its tests so evidence cannot
# silently outlive a change to the machinery that produced or checks it.
SOURCE_FILES = (
    "acceptance_harness.py",
    "tests/test_acceptance.py",
    "run_evidence.py",
    "verify_evidence.py",
)
CONTRACT_CASES = [
    "L1 hit", "L2 miss/fallback + L2->L1 backfill",
    "synchronous L1 write + durable outbox enqueue",
    "consolidation promotion + reconciliation", "deterministic identity/idempotent replay",
    "changed payload revision/tombstone", "metadata provenance envelope",
    "L2 outage + stale-while-revalidate", "bounded retries/quarantine/replay",
    "profile/bank isolation", "one composite provider/tool namespace",
]


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def source_hashes() -> dict[str, str]:
    return {name: sha256_bytes((ROOT / name).read_bytes()) for name in SOURCE_FILES}


def source_manifest_hash(hashes: dict[str, str]) -> str:
    payload = json.dumps(hashes, sort_keys=True, separators=(",", ":")).encode()
    return sha256_bytes(payload)


def stable_test_output(value: str) -> str:
    """Remove unittest's nondeterministic elapsed-time rendering before hashing."""
    return re.sub(r"(Ran \d+ tests? in )\d+(?:\.\d+)?s", r"\g<1><elapsed>", value)


def git(*args: str) -> str:
    return subprocess.check_output(["git", "-C", str(REPO_ROOT), *args], text=True).strip()


def worktree_state() -> list[str]:
    # evidence.json is generated by this command, so it is deliberately not
    # part of the state it records. All source and unrelated working-tree
    # changes remain visible and are bound to the evidence.
    evidence_rel = "prototype-acceptance-handoff/evidence.json"
    paths = []
    for line in git("status", "--porcelain=v1", "--untracked-files=all").splitlines():
        if not line:
            continue
        # Porcelain v1 normally has two status columns and a separating space
        # (" M path"), but accepting the compact "M path" form makes this
        # parser safe for mocked/portable git output too.
        path = line[3:] if len(line) > 2 and line[2] == " " else line[2:]
        path = path.lstrip()
        if path != evidence_rel:
            paths.append(line)
    return paths


# Keep the environment bounded and prevent an ambient PYTHONPATH from changing the harness.
env = dict(os.environ)
env.pop("PYTHONPATH", None)
env["PYTHONDONTWRITEBYTECODE"] = "1"
env["PYTHONHASHSEED"] = "0"
run = subprocess.run(FIXED_COMMAND, cwd=REPO_ROOT, env=env, text=True, capture_output=True)
hashes = source_hashes()
runner_hash = sha256_bytes(pathlib.Path(__file__).read_bytes())
verifier_path = ROOT / "verify_evidence.py"
verifier_hash = sha256_bytes(verifier_path.read_bytes())
worktree = worktree_state()
worktree_hash = sha256_bytes("\n".join(worktree).encode())
summary = {
    "harness": "08-prototype-acceptance-handoff",
    "status": "PASS" if run.returncode == 0 else "FAIL",
    "release_gate_status": "BLOCKED",
    "evidence_classification": {
        "catalog_status": "NON_CATALOG",
        "boundary": "FAKE_BOUNDARY",
        "release_gate_valid": False,
        "reason": "Prototype tests use stdlib fakes and a local file-backed outbox; they do not exercise the pinned real Hermes loader, a release artifact, a declared matrix cell, or release-gate provenance.",
    },
    "test_exit_code": run.returncode,
    "test_command": DISPLAY_COMMAND,
    "test_cwd": ".",
    "test_argv": FIXED_COMMAND,
    "test_stdout": run.stdout,
    "test_stderr": run.stderr,
    "test_stdout_sha256": sha256_bytes(stable_test_output(run.stdout).encode()),
    "test_stderr_sha256": sha256_bytes(stable_test_output(run.stderr).encode()),
    "source_files": hashes,
    "source_manifest_sha256": source_manifest_hash(hashes),
    "provenance": {
        "repository_root": ".",
        "source_revision": git("rev-parse", "HEAD"),
        "worktree_dirty": bool(worktree),
        "worktree_status": worktree,
        "worktree_status_sha256": worktree_hash,
        "runner_source_sha256": runner_hash,
        "verifier_source_sha256": verifier_hash,
        "interpreter": sys.version,
        "interpreter_executable": sys.executable,
        "platform": platform.platform(),
        "python_implementation": platform.python_implementation(),
    },
    "contract_cases": CONTRACT_CASES,
    "scope": "stdlib fakes and local file-backed outbox only; no live integration or production changes",
}
(ROOT / "evidence.json").write_text(json.dumps(summary, indent=2) + "\n")
print(json.dumps({k: summary[k] for k in ("harness", "status", "test_exit_code", "contract_cases", "scope")}, indent=2))
sys.exit(run.returncode)
